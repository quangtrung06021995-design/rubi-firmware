# Converts icons/nen_menu.png into main/display/rubi_bg.h (LVGL RGB565 image 144x108 (shown scaled to 320x240), background of the first menu page).
# Run from overlay/:  python3 ../patches/make_bg.py ../icons/nen_menu.png
import sys
from PIL import Image
W, H = 144, 108   # drawn 2.222x larger on the 320x240 screen (a full-size picture would not fit in the app partition)
src = sys.argv[1] if len(sys.argv) > 1 else '../icons/nen_menu.png'
im = Image.open(src).convert('RGB').resize((W, H), Image.LANCZOS)
data = bytearray()
for r, g, b in im.getdata():
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    data += bytes((v & 0xFF, v >> 8))
out = ['// Generated by patches/make_bg.py - do not edit.', '#pragma once', '#include <lvgl.h>', '', 'static const uint8_t rubi_bg_menu_map[] = {']
for i in range(0, len(data), 24):
    out.append('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
out += ['};', 'static const lv_image_dsc_t rubi_bg_menu = {',
        '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, .w = %d, .h = %d, .stride = %d, .reserved_2 = 0 },' % (W, H, W * 2),
        '  .data_size = %d,' % len(data), '  .data = rubi_bg_menu_map,', '};', '']
open('main/display/rubi_bg.h', 'w').write('\n'.join(out))
print('bg written', len(data))
