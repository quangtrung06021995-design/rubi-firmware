# Converts icons/math/*.png (button pictures drawn for the maths screen) into main/display/rubi_math_icons.h
# as LVGL RGB565A8 images (RGB565 plane + 8-bit alpha plane). Run from overlay/:  python3 ../patches/make_math_icons.py ../icons/math
import sys, os
import numpy as np
from PIL import Image, ImageDraw

src = sys.argv[1] if len(sys.argv) > 1 else '../icons/math2'
out = ['// Generated by patches/make_math_icons.py - do not edit.', '#pragma once', '#include <lvgl.h>', '']

def emit(name, im):
    im = im.convert('RGBA')
    w, h = im.size
    a = np.array(im)
    r = a[..., 0].astype(np.uint16); g = a[..., 1].astype(np.uint16); b = a[..., 2].astype(np.uint16)
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    data = bytearray()
    for x in v.flatten():
        data += bytes((int(x) & 0xFF, int(x) >> 8))
    data += bytes(a[..., 3].flatten().tolist())
    out.append('static const uint8_t rubi_m_%s_map[] = {' % name)
    for i in range(0, len(data), 32):
        out.append('  ' + ','.join(str(x) for x in data[i:i + 32]) + ',')
    out.append('};')
    out.append('static const lv_image_dsc_t rubi_m_%s = {' % name)
    out.append('  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = %d, .h = %d, .stride = %d, .reserved_2 = 0 },' % (w, h, w * 2))
    out.append('  .data_size = %d,' % len(data))
    out.append('  .data = rubi_m_%s_map,' % name)
    out.append('};')
    out.append('')

def load_button(n, W, H, shape=None):
    """Crop to the picture and scale to WxH (the sheet pictures are already clean, with transparent corners)."""
    im = Image.open(os.path.join(src, n + '.png')).convert('RGBA')
    bb = im.getchannel('A').point(lambda p: 255 if p > 20 else 0).getbbox()
    im = im.crop(bb)
    if H == 0:
        H = max(4, round(im.size[1] * W / im.size[0]))
    return im.resize((W, H), Image.LANCZOS)

for d in range(10):
    emit('k%d' % d, load_button('number_%d' % d, 62, 31))
emit('kdel', load_button('delete', 62, 31))
emit('kok', load_button('ok', 66, 31))
emit('listen', load_button('listen', 78, 31))
emit('speaker', load_button('speaker', 34, 34))
emit('back', load_button('back', 34, 34))

# Big digits / signs, drawn with a bold font in the colours of the mockup (the digit pictures of the zip are not clean enough).
from PIL import ImageFont
FONT = '/usr/share/fonts/truetype/google-fonts/Poppins-Bold.ttf'
def glyph(ch, color, H):
    f = ImageFont.truetype(FONT, H * 4)
    tmp = Image.new('L', (H * 8, H * 8), 0)
    ImageDraw.Draw(tmp).text((H, H), ch, font=f, fill=255)
    bb = tmp.getbbox()
    A = tmp.crop(bb)
    w = max(4, round(A.size[0] * H / A.size[1]))
    A = A.resize((w, H), Image.LANCZOS)
    rgb = Image.new('RGB', A.size, color)
    rgb.putalpha(A)
    return rgb

for d in range(10):
    emit('g%d' % d, glyph(str(d), (0x0B, 0x2E, 0x94), 26))   # question bar
emit('gq', glyph('?', (0xFF, 0x8A, 0x00), 26))

emit('gplus', load_button('plus', 24, 0))
emit('gminus', load_button('minus', 24, 0))
emit('geq', load_button('equals', 24, 0))

open('main/display/rubi_math_icons.h', 'w').write('\n'.join(out))
print('math icons written')
