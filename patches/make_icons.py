# Converts icons/*.png into main/display/rubi_icons.h (LVGL RGB565 images, 88x88, white background).
import os, sys
from PIL import Image

SIZE = 88
names = ['nghe_nhac', 'wifi', 'chinh_cam_ung', 'dong', 'song_ngu', 'hoc_trai_cay', 'hoc_dong_vat', 'hoc_do_vat', 'hoc_hinh_khoi', 'truyen_tranh', 'cai_dat', 'choi_cung']
src = sys.argv[1] if len(sys.argv) > 1 else '../icons'
out = ['// Generated by patches/make_icons.py - do not edit.', '#pragma once', '#include <lvgl.h>', '']
for n in names:
    path = os.path.join(src, n + '.png')
    im = Image.open(path).convert('RGBA')
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert('RGB')
    im.thumbnail((SIZE, SIZE), Image.LANCZOS)
    canvas = Image.new('RGB', (SIZE, SIZE), (255, 255, 255))
    canvas.paste(im, ((SIZE - im.size[0]) // 2, (SIZE - im.size[1]) // 2))
    data = bytearray()
    for r, g, b in canvas.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    out.append('static const uint8_t rubi_icon_%s_map[] = {' % n)
    for i in range(0, len(data), 24):
        out.append('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
    out.append('};')
    out.append('static const lv_image_dsc_t rubi_icon_%s = {' % n)
    out.append('  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, '
               '.w = %d, .h = %d, .stride = %d, .reserved_2 = 0 },' % (SIZE, SIZE, SIZE * 2))
    out.append('  .data_size = %d,' % len(data))
    out.append('  .data = rubi_icon_%s_map,' % n)
    out.append('};')
    out.append('')
open('main/display/rubi_icons.h', 'w').write('\n'.join(out))
print('icons written')
