# Converts icons/*.png into main/display/rubi_icons.h (LVGL RGB565 images, 88x88, white background).
import os, sys
from PIL import Image

SIZE = 88
names = ['nghe_nhac', 'wifi', 'chinh_cam_ung', 'dong', 'song_ngu', 'hoc_trai_cay', 'hoc_dong_vat', 'hoc_do_vat', 'hoc_hinh_khoi', 'truyen_tranh', 'cai_dat', 'choi_cung', 'toan_lop1', 'dong_ho', 'tieng_anh', 'am_luong', 'wifi_s', 'dieu_khien', 'cam_ung_s', 'quay_lai', 'nhay_mua', 'hat_ru', 'hen_gio']
# Icons of the first menu page sit on a pale-blue card (CARD), so their white outer background is replaced by that colour.
CARD = (0xDD, 0xEF, 0xFC)
ON_CARD = {'nghe_nhac', 'song_ngu', 'truyen_tranh', 'toan_lop1', 'dong_ho', 'choi_cung', 'cai_dat', 'tieng_anh'}
# Icons on the pale-purple (0xF0E9FF) background of the inner menu pages: their white outer background is recoloured too.
LAV = (0xF0, 0xE9, 0xFF)
ON_LAV = {'dong', 'hoc_trai_cay', 'hoc_dong_vat', 'hoc_do_vat', 'hoc_hinh_khoi'}
# Small icons at the left of the list rows (row colour 0xE6F0FF), stored at 30 px.
ROW = (0xE6, 0xF0, 0xFF)
ON_ROW = {'am_luong', 'wifi_s', 'dieu_khien', 'cam_ung_s', 'quay_lai', 'nhay_mua', 'hat_ru', 'hen_gio'}
SRC_OF = {}
src = sys.argv[1] if len(sys.argv) > 1 else '../icons'
out = ['// Generated by patches/make_icons.py - do not edit.', '#pragma once', '#include <lvgl.h>', '']
for n in names:
    path = os.path.join(src, SRC_OF.get(n, n) + '.png')
    im = Image.open(path).convert('RGBA')
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert('RGB')
    fill = (255, 255, 255)
    if n in ON_CARD or n in ON_LAV or n in ON_ROW:
        BG = CARD if n in ON_CARD else (ROW if n in ON_ROW else LAV)
        import numpy as np
        from scipy import ndimage
        a = np.array(im).astype(float)
        light = a.min(axis=2) >= 245
        lab, _ = ndimage.label(light)
        border = set(lab[0, :]) | set(lab[-1, :]) | set(lab[:, 0]) | set(lab[:, -1])
        border.discard(0)
        alpha = ndimage.gaussian_filter(np.where(np.isin(lab, list(border)), 0.0, 1.0), 1.0)[..., None]
        blend = a * alpha + np.array(BG, float) * (1 - alpha)
        im = Image.fromarray(blend.astype('uint8'))
        fill = BG
    S = 30 if n in ON_ROW else (72 if n in ON_CARD else SIZE)   # first-page icons are stored at the 72 px they are shown at (saves flash)
    im.thumbnail((S, S), Image.LANCZOS)
    canvas = Image.new('RGB', (S, S), fill)
    canvas.paste(im, ((S - im.size[0]) // 2, (S - im.size[1]) // 2))
    data = bytearray()
    for r, g, b in canvas.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    out.append('static const uint8_t rubi_icon_%s_map[] = {' % n)
    for i in range(0, len(data), 24):
        out.append('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
    out.append('};')
    out.append('static const lv_image_dsc_t rubi_icon_%s = {' % n)
    out.append('  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, '
               '.w = %d, .h = %d, .stride = %d, .reserved_2 = 0 },' % (S, S, S * 2))
    out.append('  .data_size = %d,' % len(data))
    out.append('  .data = rubi_icon_%s_map,' % n)
    out.append('};')
    out.append('')
open('main/display/rubi_icons.h', 'w').write('\n'.join(out))
print('icons written')
