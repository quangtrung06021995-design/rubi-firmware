# Tao overlay/main/display/rubi_viec_icons.h: 8 icon viec 140x140 (the nhac viec tren man hinh Rubi) + icon lich 30x30 (dong "Thoi gian bieu").
# Nguon: icons/viec/*.png (RGB565 little-endian, kieu LVGL nhu rubi_icons.h)
from PIL import Image
names = ['viec_danh_rang', 'viec_an_com', 'viec_hoc_bai', 'viec_di_tam', 'viec_di_ngu', 'viec_don_do_choi', 'viec_uong_nuoc', 'viec_doc_sach']
ROW = (0xE6, 0xF0, 0xFF)
out = ['// Generated by tools/make_screen_viec.py - do not edit.', '#pragma once', '#include <lvgl.h>', '']
def add(var, im, S, bg):
    im = im.convert('RGB').resize((S, S), Image.LANCZOS)
    data = bytearray()
    for r, g, b in im.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    out.append('static const uint8_t %s_map[] = {' % var)
    for i in range(0, len(data), 24): out.append('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
    out.append('};')
    out.append('static const lv_image_dsc_t %s = {' % var)
    out.append('  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, .w = %d, .h = %d, .stride = %d, .reserved_2 = 0 },' % (S, S, S * 2))
    out.append('  .data_size = %d,' % len(data))
    out.append('  .data = %s_map,' % var)
    out.append('};')
    out.append('')
for i, n in enumerate(names): add('rubi_viec_big_%d' % i, Image.open(f'icons/viec/{n}.png'), 140, None)
add('rubi_icon_lich', Image.open('icons/viec/thoi_gian_bieu.png'), 30, ROW)
out.append('static const lv_image_dsc_t* const rubi_viec_big[8] = {%s};' % ','.join('&rubi_viec_big_%d' % i for i in range(8)))
open('overlay/main/display/rubi_viec_icons.h', 'w').write('\n'.join(out) + '\n')
print('ok')
