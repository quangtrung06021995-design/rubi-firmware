#!/usr/bin/env python3
"""Cat 4 khung hinh chim canh cut (2x2) thanh 4 anh 320x240 (palette+RLE) cho Rubi khi dang noi.

Khung: 0 = mat mo, mo dong   1 = mat mo, mo nua   2 = mat mo, mo rong   3 = mat nham (chop), mo nua
Dau vao: icons/noi_4_khung.png     Dau ra: overlay/main/display/rubi_talk_data.h
Dau chim duoc dat cung vi tri/kich thuoc nhu bo 20 mat cu (rong 242 px, tam giua x=159.5, y=119.5)
de khi doi khung khong bi nhay.
"""
import itertools, os, struct, sys
import numpy as np
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(root, 'icons', 'noi_4_khung.png')
dst = os.path.join(root, 'overlay', 'main', 'display', 'rubi_talk_data.h')

im = Image.open(src).convert('RGB')
a = np.array(im)
nonwhite = (a < 240).any(axis=2)

def blank_runs(prof):
    idx = [i for i, v in enumerate(prof) if v == 0]
    out = []
    for _, g in itertools.groupby(enumerate(idx), lambda t: t[1] - t[0]):
        g = list(g)
        out.append((g[0][1], g[-1][1]))
    return out

def gaps(prof):
    """Bo hai dau (le trang), giu cac khoang trang o giua."""
    r = blank_runs(prof)
    return [g for g in r if g[0] > 0 and g[1] < len(prof) - 1]

ys = gaps(nonwhite.sum(axis=1))
xs = gaps(nonwhite.sum(axis=0))
if len(ys) != 1 or len(xs) != 1:
    sys.exit('Khong tach duoc luoi 2x2: %s %s' % (ys, xs))
ycut = (ys[0][0] + ys[0][1]) // 2
xcut = (xs[0][0] + xs[0][1]) // 2
cells = [(0, xcut, 0, ycut), (xcut, im.width, 0, ycut), (0, xcut, ycut, im.height), (xcut, im.width, ycut, im.height)]

# Ket cau dau cu: rong 242 (x 39..280), cao 210 (y 15..224)
TARGET_W = 242.0
CX, CY = 159.5, 119.5

def pack(img):
    q = img.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:768]
    n = len(pal) // 3
    pal565 = []
    for i in range(256):
        r, g, b = (pal[3 * i], pal[3 * i + 1], pal[3 * i + 2]) if i < n else (255, 255, 255)
        pal565.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    idx = list(q.getdata())
    out = bytearray(struct.pack('<H', 256))
    for v in pal565:
        out += struct.pack('<H', v)
    i = 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i] and j - i < 255:
            j += 1
        out += bytes([j - i, idx[i]])
        i = j
    return bytes(out)

blobs = []
for k, (x0, x1, y0, y1) in enumerate(cells):
    c = im.crop((x0, y0, x1, y1))
    m = (np.array(c) < 240).any(axis=2)
    yy, xx = np.where(m)
    bx0, by0, bx1, by1 = xx.min(), yy.min(), xx.max(), yy.max()
    head = c.crop((bx0, by0, bx1 + 1, by1 + 1))
    s = TARGET_W / head.width
    nw, nh = round(head.width * s), round(head.height * s)
    head = head.resize((nw, nh), Image.LANCZOS)
    canvas = Image.new('RGB', (320, 240), (255, 255, 255))
    canvas.paste(head, (round(CX - nw / 2), round(CY - nh / 2)))
    canvas.save(os.path.join(root, 'icons', 'noi_khung_%d.png' % k))
    blobs.append(pack(canvas))
    print('khung', k, 'dau', head.size, 'bytes', len(blobs[-1]))

with open(dst, 'w') as f:
    f.write('// Generated by tools/tao_khung_noi.py: 4 talking frames 320x240 (palette+RLE). Do not edit.\n')
    f.write('#ifndef RUBI_TALK_DATA_H\n#define RUBI_TALK_DATA_H\n#include <cstdint>\n#include <cstddef>\n\n')
    for k, b in enumerate(blobs):
        f.write('static const uint8_t kRubiTalk%d[] = {%s};\n' % (k, ','.join(str(v) for v in b)))
    f.write('static const uint8_t* const kRubiTalkData[4] = {kRubiTalk0,kRubiTalk1,kRubiTalk2,kRubiTalk3};\n')
    f.write('static const size_t kRubiTalkSize[4] = {sizeof(kRubiTalk0),sizeof(kRubiTalk1),sizeof(kRubiTalk2),sizeof(kRubiTalk3)};\n')
    f.write('\n#endif  // RUBI_TALK_DATA_H\n')
print('ghi', dst)
